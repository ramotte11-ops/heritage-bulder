import { describe, expect, it, vi } from "vitest";
import type { MemorialContent } from "@/types/memorial";
import { fullAnnouncement, recordingResolver, FIXTURE_HERO_MEDIA_ID } from "@/lib/memorial/assembly/test-fixtures";
import { computePublicationPreview } from "./publication-preview";
import { FreePublicationRefusedError } from "./publish-memorial";
import {
  EmailVerificationRequiredError,
  HeroPhotoRequiredError,
  publicationOutcomeOf,
  publishFromPreview,
  type MemorialFirstPublicationRepository,
} from "./publish-from-preview";

const MEMORIAL_ID = "11111111-1111-4111-8111-111111111111";
const OWNER_ID = "22222222-2222-4222-8222-222222222222";
const galleryId = (n: number) => `5e0c2a4b-1f3d-4e6a-8b7c-${String(n).padStart(12, "0")}`;

function withGallery(count: number): MemorialContent {
  return {
    ...fullAnnouncement(),
    gallery: { items: Array.from({ length: count }, (_, i) => ({ mediaId: galleryId(i + 1), caption: null })) },
  } as MemorialContent;
}

function snapshot(overrides: Record<string, unknown> = {}, content: MemorialContent = fullAnnouncement()) {
  return {
    status: "draft" as const,
    firstPublishedAt: null,
    language: "fr" as const,
    skin: "intemporel" as const,
    skinVariant: "light" as const,
    slug: "jeanne-martin",
    accessLevel: "avis",
    draft: { content, updatedAt: "2026-11-02T06:00:00Z", revision: 7 },
    ...overrides,
  };
}

function digestOf(current: ReturnType<typeof snapshot>, gallerySelection?: unknown) {
  const preview = computePublicationPreview({
    draft: current.draft.content,
    accessLevel: current.accessLevel,
    skin: current.skin,
    requestedSelection: gallerySelection,
  });
  if (!preview.ok) throw new Error("preview refused");
  return preview.digest;
}

function repository(current = snapshot(), commit?: () => Promise<unknown>) {
  const commitFirstPublication = vi.fn(
    commit ??
      (async () => ({
        outcome: "published",
        publishedAt: "2026-11-02T07:00:00Z",
        firstPublishedAt: "2026-11-02T07:00:00Z",
        revision: current.draft.revision,
        slug: current.slug ?? "10d63bbb38ba",
      })),
  );
  return {
    value: { load: vi.fn().mockResolvedValue(current), commitFirstPublication } as unknown as MemorialFirstPublicationRepository,
    commitFirstPublication,
  };
}

const input = (current: ReturnType<typeof snapshot>, extra: Record<string, unknown> = {}) => ({
  memorialId: MEMORIAL_ID,
  ownerId: OWNER_ID,
  expectedRevision: current.draft.revision,
  expectedDigest: digestOf(current, extra.gallerySelection),
  ...extra,
});

describe("publishFromPreview — Lot 3 v4: the public slug is generated by the database", () => {
  it("a memorial WITHOUT slug (the S1 case) is published: expectedSlug NULL, the generated slug returned", async () => {
    const current = snapshot({ slug: null });
    const repo = repository(current);
    const result = await publishFromPreview({ repository: repo.value, resolveMedia: recordingResolver().resolve }, input(current));
    expect(result).toMatchObject({ ok: true, outcome: "published", slug: "10d63bbb38ba" });
    expect(repo.commitFirstPublication).toHaveBeenCalledOnce();
    const commit = (repo.commitFirstPublication.mock.calls as unknown as unknown[][])[0][0] as unknown as Record<string, unknown>;
    expect(commit.expectedSlug).toBeNull();
  });

  it("a stored slug is passed as the expected one (never regenerated here)", async () => {
    const current = snapshot();
    const repo = repository(current);
    await publishFromPreview({ repository: repo.value, resolveMedia: recordingResolver().resolve }, input(current));
    const commit = (repo.commitFirstPublication.mock.calls as unknown as unknown[][])[0][0] as unknown as Record<string, unknown>;
    expect(commit.expectedSlug).toBe("jeanne-martin");
  });

  it.each([[""], ["   "]])("a blank stored slug (%j) is refused before any commit", async (slug) => {
    const current = snapshot({ slug });
    const repo = repository(current);
    const result = await publishFromPreview({ repository: repo.value, resolveMedia: recordingResolver().resolve }, input(current));
    expect(result).toEqual({ ok: false, code: "not_publishable" });
    expect(repo.commitFirstPublication).not.toHaveBeenCalled();
  });

  it("no language → not_publishable, nothing committed (unchanged)", async () => {
    const current = snapshot({ language: null, slug: null });
    const repo = repository(current);
    const result = await publishFromPreview({ repository: repo.value, resolveMedia: recordingResolver().resolve }, input(current));
    expect(result).toEqual({ ok: false, code: "not_publishable" });
    expect(repo.commitFirstPublication).not.toHaveBeenCalled();
  });
});

describe("publishFromPreview — the confirmed publication", () => {
  it("publishes the server projection (never the raw draft) for the stored level, through ONE commit", async () => {
    const current = snapshot({}, withGallery(7));
    const repo = repository(current);
    const result = await publishFromPreview({ repository: repo.value, resolveMedia: recordingResolver().resolve }, input(current));
    expect(result).toMatchObject({ ok: true, outcome: "published", revision: 7 });
    expect(repo.commitFirstPublication).toHaveBeenCalledOnce();
    const commit = (repo.commitFirstPublication.mock.calls as unknown as unknown[][])[0][0] as unknown as Record<string, unknown>;
    expect(commit).toMatchObject({ memorialId: MEMORIAL_ID, ownerId: OWNER_ID, expectedRevision: 7, expectedAccessLevel: "avis", expectedSlug: "jeanne-martin" });
    expect(commit.expectedContent).toBe(current.draft.content);
    const published = commit.publishedContent as { gallery: { items: Array<{ mediaId: string }> } };
    expect(published.gallery.items.map(({ mediaId }) => mediaId)).toEqual([1, 2, 3, 4, 5, 6].map(galleryId));
  });

  it("publishes exactly the family's gallery choice, in the Builder's order", async () => {
    const current = snapshot({}, withGallery(8));
    const repo = repository(current);
    const choice = [galleryId(8), galleryId(1)];
    await publishFromPreview({ repository: repo.value, resolveMedia: recordingResolver().resolve }, input(current, { gallerySelection: choice }));
    const commit = (repo.commitFirstPublication.mock.calls as unknown as unknown[][])[0][0] as unknown as { publishedContent: { gallery: { items: Array<{ mediaId: string }> } } };
    expect(commit.publishedContent.gallery.items.map(({ mediaId }) => mediaId)).toEqual([galleryId(1), galleryId(8)]);
  });

  it("a fingerprint that is not the recomputed one is refused (preview_outdated), nothing committed", async () => {
    const current = snapshot({}, withGallery(7));
    const repo = repository(current);
    const result = await publishFromPreview(
      { repository: repo.value, resolveMedia: recordingResolver().resolve },
      { ...input(current), gallerySelection: [galleryId(7)] },
    );
    expect(result).toEqual({ ok: false, code: "preview_outdated" });
    expect(repo.commitFirstPublication).not.toHaveBeenCalled();
  });

  it("an access level changed since the Preview (upgrade to complet) is refused as outdated", async () => {
    const seen = snapshot({}, withGallery(7));
    const now = snapshot({ accessLevel: "complet" }, withGallery(7));
    const repo = repository(now);
    const result = await publishFromPreview({ repository: repo.value, resolveMedia: recordingResolver().resolve }, input(seen));
    expect(result).toEqual({ ok: false, code: "preview_outdated" });
    expect(repo.commitFirstPublication).not.toHaveBeenCalled();
  });

  it("a stale revision is refused before anything is computed", async () => {
    const current = snapshot();
    const repo = repository(current);
    const result = await publishFromPreview({ repository: repo.value, resolveMedia: recordingResolver().resolve }, { ...input(current), expectedRevision: 6 });
    expect(result).toEqual({ ok: false, code: "revision_conflict" });
    expect(repo.commitFirstPublication).not.toHaveBeenCalled();
  });

  it.each([
    ["no main photo", { ...fullAnnouncement(), hero: { ...(fullAnnouncement() as { hero: object }).hero, photo: null } }],
  ])("%s → hero_photo_required, nothing committed (the draft stays saveable)", async (_label, content) => {
    const current = snapshot({}, content as MemorialContent);
    const repo = repository(current);
    const result = await publishFromPreview({ repository: repo.value, resolveMedia: recordingResolver().resolve }, input(current));
    expect(result).toEqual({ ok: false, code: "hero_photo_required" });
    expect(repo.commitFirstPublication).not.toHaveBeenCalled();
  });

  it("a main photo that cannot be resolved (missing, not ready, retired) → hero_photo_required", async () => {
    const current = snapshot();
    const repo = repository(current);
    const resolver = recordingResolver((request) => (request.purpose === "hero" ? null : { mediaId: request.mediaId, readUrl: "u" }));
    const result = await publishFromPreview({ repository: repo.value, resolveMedia: resolver.resolve }, input(current));
    expect(result).toEqual({ ok: false, code: "hero_photo_required" });
    expect(resolver.calls[0]).toEqual({ mediaId: FIXTURE_HERO_MEDIA_ID, purpose: "hero" });
    expect(repo.commitFirstPublication).not.toHaveBeenCalled();
  });

  it.each([
    ["ready (legacy v2 path)", { status: "ready" }],
    ["editing (republication, out of scope)", { status: "editing", firstPublishedAt: "2026-10-01T00:00:00Z" }],
    ["archived", { status: "archived" }],
  ])("a memorial in %s is not published from the Preview", async (_label, overrides) => {
    const current = snapshot(overrides);
    const repo = repository(current);
    const result = await publishFromPreview({ repository: repo.value, resolveMedia: recordingResolver().resolve }, input(current));
    expect(result).toEqual({ ok: false, code: "invalid_transition" });
    expect(repo.commitFirstPublication).not.toHaveBeenCalled();
  });

  it("no memorial (or not this owner's) → not_found_or_forbidden", async () => {
    const repo = repository();
    (repo.value.load as ReturnType<typeof vi.fn>).mockResolvedValue(null);
    const result = await publishFromPreview({ repository: repo.value, resolveMedia: recordingResolver().resolve }, input(snapshot()));
    expect(result).toEqual({ ok: false, code: "not_found_or_forbidden" });
  });
});

describe("publishFromPreview — second calls and database refusals", () => {
  it("an already published memorial is NOT reported as success by the application: the database must prove it", async () => {
    const current = snapshot({ status: "published", firstPublishedAt: "2026-11-02T07:00:00Z" });
    const repo = repository(current, async () => ({ outcome: "already_published", publishedAt: "p", firstPublishedAt: "f", revision: 7 }));
    const result = await publishFromPreview({ repository: repo.value, resolveMedia: recordingResolver().resolve }, input(current));
    expect(repo.commitFirstPublication).toHaveBeenCalledOnce();
    expect(result).toMatchObject({ ok: true, outcome: "already_published" });
  });

  it("when the database cannot prove the identity (40001) → publication_conflict, never a success", async () => {
    const current = snapshot({ status: "published", firstPublishedAt: "2026-11-02T07:00:00Z" });
    const conflict = Object.assign(new Error("conflict"), { code: "MEMORIAL_PUBLICATION_CONFLICT" });
    const repo = repository(current, async () => Promise.reject(conflict));
    const result = await publishFromPreview({ repository: repo.value, resolveMedia: recordingResolver().resolve }, input(current));
    expect(result).toEqual({ ok: false, code: "publication_conflict" });
  });

  it.each([
    ["HD422", new HeroPhotoRequiredError(), "hero_photo_required"],
    ["HD410", new FreePublicationRefusedError("free_window_closed"), "free_window_closed"],
    ["HD403 quota", new FreePublicationRefusedError("free_quota_reached"), "free_quota_reached"],
    ["HD413", new FreePublicationRefusedError("free_content_refused"), "free_content_refused"],
    ["23514", Object.assign(new Error("rejected"), { code: "MEMORIAL_PUBLICATION_REJECTED" }), "not_publishable"],
  ])("database refusal %s → %s", async (_label, error, code) => {
    const current = snapshot();
    const repo = repository(current, async () => Promise.reject(error));
    const result = await publishFromPreview({ repository: repo.value, resolveMedia: recordingResolver().resolve }, input(current));
    expect(result).toEqual({ ok: false, code });
  });

  it("an unexpected error is not swallowed here (the action answers « failed »)", async () => {
    const current = snapshot();
    const repo = repository(current, async () => Promise.reject(new Error("network down")));
    await expect(publishFromPreview({ repository: repo.value, resolveMedia: recordingResolver().resolve }, input(current))).rejects.toThrow("network down");
  });
});

describe("publicationOutcomeOf — what the Builder shows", () => {
  it.each([
    [{ ok: true, outcome: "published", publishedAt: "", firstPublishedAt: "", revision: 1 }, "published"],
    [{ ok: true, outcome: "already_published", publishedAt: "", firstPublishedAt: "", revision: 1 }, "already_published"],
    [{ ok: false, code: "hero_photo_required" }, "hero_photo_required"],
    [{ ok: false, code: "revision_conflict" }, "preview_outdated"],
    [{ ok: false, code: "preview_outdated" }, "preview_outdated"],
    [{ ok: false, code: "publication_conflict" }, "preview_outdated"],
    [{ ok: false, code: "free_window_closed" }, "free_window_closed"],
    [{ ok: false, code: "free_quota_reached" }, "free_quota_reached"],
    [{ ok: false, code: "not_found_or_forbidden" }, "access_refused"],
    [{ ok: false, code: "signed_out" }, "signed_out"],
    [{ ok: false, code: "invalid_transition" }, "failed"],
    [{ ok: false, code: "free_content_refused" }, "failed"],
  ] as const)("%j → %s", (result, outcome) => {
    expect(publicationOutcomeOf(result as never)).toBe(outcome);
  });
});

describe("publishFromPreview — QG 004-B: the owner's address must be proven", () => {
  it("refuses before any commit when HERITAGE's proof is missing", async () => {
    const current = snapshot();
    const repo = repository(current);
    const isOwnerEmailVerified = vi.fn().mockResolvedValue(false);
    const result = await publishFromPreview(
      { repository: repo.value, resolveMedia: recordingResolver().resolve, isOwnerEmailVerified },
      input(current),
    );
    expect(result).toEqual({ ok: false, code: "email_unverified" });
    expect(isOwnerEmailVerified).toHaveBeenCalledWith(OWNER_ID);
    expect(repo.commitFirstPublication).not.toHaveBeenCalled();
    expect(publicationOutcomeOf(result)).toBe("email_unverified");
  });

  it("publishes once the proof exists", async () => {
    const current = snapshot();
    const repo = repository(current);
    const result = await publishFromPreview(
      { repository: repo.value, resolveMedia: recordingResolver().resolve, isOwnerEmailVerified: vi.fn().mockResolvedValue(true) },
      input(current),
    );
    expect(result).toMatchObject({ ok: true, outcome: "published" });
  });

  it("maps the database's own refusal (HV403 → EmailVerificationRequiredError) even when the pre-check passed", async () => {
    const current = snapshot();
    const repo = repository(current, async () => {
      throw new EmailVerificationRequiredError();
    });
    const result = await publishFromPreview(
      { repository: repo.value, resolveMedia: recordingResolver().resolve, isOwnerEmailVerified: vi.fn().mockResolvedValue(true) },
      input(current),
    );
    expect(result).toEqual({ ok: false, code: "email_unverified" });
  });
});
